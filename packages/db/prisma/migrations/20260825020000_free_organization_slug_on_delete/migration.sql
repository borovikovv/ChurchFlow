-- Видалення організації м'яке: status = DELETED і проставлений deleted_at, рядок лишається.
-- Глобальна унікальність slug тримала ім'я зайнятим назавжди, тож повторно створити
-- організацію з тим самим slug було неможливо. Тепер зайнятими вважаються лише невидалені.
--
-- Сам slug не чіпаємо: він потрібен для відновлення (RESTORE) і для історії.
-- Ціна в тому, що відновлення впаде, якщо ім'я тим часом зайняли — це обробляється в коді.

DROP INDEX "organizations_slug_key";

CREATE UNIQUE INDEX "organizations_slug_active_key"
  ON "organizations"("slug")
  WHERE "deleted_at" IS NULL;
